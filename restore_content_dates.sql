  _mismatch text;
BEGIN
  WITH import_counts(channel_label, cnt) AS (
    VALUES
      ('Articles', 104::bigint),
      ('Blog', 104::bigint),
      ('Email', 208::bigint),
      ('Facebook', 364::bigint),
      ('Instagram', 312::bigint),
      ('LinkedIn', 369::bigint),
      ('X', 364::bigint),
      ('YouTube', 156::bigint)
  ),
  live_counts AS (
    SELECT channel_label, count(*) AS cnt
    FROM public.content_schedule
    GROUP BY channel_label
  ),
  mismatches AS (
    SELECT COALESCE(i.channel_label, l.channel_label) AS ch,
           COALESCE(i.cnt, 0) AS import_cnt,
           COALESCE(l.cnt, 0) AS live_cnt
    FROM import_counts i
    FULL OUTER JOIN live_counts l USING (channel_label)
    WHERE COALESCE(i.cnt, 0) <> COALESCE(l.cnt, 0)
  )
  SELECT string_agg(ch || ': import=' || import_cnt || ' live=' || live_cnt, '; ')
    INTO _mismatch
    FROM mismatches;

  IF _mismatch IS NOT NULL THEN
    RAISE EXCEPTION 'Channel count mismatch — aborting: %', _mismatch;
  END IF;
END
