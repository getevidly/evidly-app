-- ZIP -> California food-safety jurisdiction lookup
-- Source: HUD-USPS ZIP-COUNTY Crosswalk, 2026 Q1 (huduser.gov). Allocation uses BUS_RATIO
-- (share of BUSINESS addresses), not residential, because the subject is commercial kitchens.
-- Generated 2026-08-16. 2443 California ZIPs; 52 flagged for review.
--
-- KNOWN LIMITS, deliberate and documented:
--   * ZIP codes do not follow city or county lines (HUD states this explicitly).
--   * VERNON cannot be resolved from a ZIP. ZIP 90058 is 100% Los Angeles County in the
--     crosswalk and USPS names it LOS ANGELES; Vernon runs its own health department.
--     90058 is therefore always flagged, never auto-assigned.
--   * BERKELEY, LONG BEACH and PASADENA are assigned from the USPS preferred city name.
--     That is right for the large majority of addresses but cannot see a city boundary,
--     so any of their ZIPs that also crosses a county line is flagged.
--   * PO Box-only ZIPs are absent from the crosswalk entirely and will not resolve.
--
-- needs_review = true means DO NOT auto-send a county briefing for this ZIP.

CREATE TABLE IF NOT EXISTS public.zip_jurisdictions (
  zip               text PRIMARY KEY,
  county_fips       text NOT NULL,
  county_name       text NOT NULL,
  city_jurisdiction text,
  bus_share         numeric NOT NULL,
  needs_review      boolean NOT NULL DEFAULT false,
  review_reason     text,
  source            text NOT NULL DEFAULT 'HUD-USPS ZIP-COUNTY Crosswalk 2026Q1',
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS zip_jurisdictions_county_fips_idx ON public.zip_jurisdictions (county_fips);
CREATE INDEX IF NOT EXISTS zip_jurisdictions_needs_review_idx ON public.zip_jurisdictions (needs_review) WHERE needs_review;

ALTER TABLE public.zip_jurisdictions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS zip_jurisdictions_service_role_all ON public.zip_jurisdictions;
CREATE POLICY zip_jurisdictions_service_role_all ON public.zip_jurisdictions
  FOR ALL TO service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS zip_jurisdictions_platform_admin_all ON public.zip_jurisdictions;
CREATE POLICY zip_jurisdictions_platform_admin_all ON public.zip_jurisdictions
  FOR ALL USING (is_platform_admin()) WITH CHECK (is_platform_admin());

